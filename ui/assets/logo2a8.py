"""Rasterise logo.svg (white line art, with blurs, masks and the "20" set in Barlow Condensed) into LVGL A8 masks.

Writes two masks cropped to the drawing: ui_logo_a8 (boot screen) and ui_logo_small_a8 (home), tinted by the UI.
Usage: python3 logo2a8.py ../logo_a8.c
Needs PyGObject with GdkPixbuf and the librsvg loader (Rocky: python3-gobject, gdk-pixbuf2, librsvg2). The fonts in
this directory are made visible to the renderer through a temporary fontconfig file; nothing is installed.
"""
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SIZES = (("ui_logo_a8", 248), ("ui_logo_small_a8", 76))  # px of the full 512-unit viewBox, before cropping


def render(px):
    import gi
    gi.require_version('GdkPixbuf', '2.0')
    from gi.repository import GdkPixbuf
    p = GdkPixbuf.Pixbuf.new_from_file_at_size(os.path.join(HERE, 'logo.svg'), px, px)
    assert p.get_has_alpha() and p.get_n_channels() == 4
    w, h, stride, raw = p.get_width(), p.get_height(), p.get_rowstride(), p.get_pixels()
    rows = [bytes(raw[y * stride + 4 * x + 3] for x in range(w)) for y in range(h)]
    ys = [y for y, r in enumerate(rows) if any(r)]
    xs = [x for x in range(w) if any(r[x] for r in rows)]
    x0, x1, y0, y1 = xs[0], xs[-1] + 1, ys[0], ys[-1] + 1
    return x1 - x0, y1 - y0, b''.join(r[x0:x1] for r in rows[y0:y1])


def main():
    out = sys.argv[1]
    with tempfile.TemporaryDirectory() as tmp:
        conf = os.path.join(tmp, 'fonts.conf')
        with open(conf, 'w') as f:
            f.write(f'<?xml version="1.0"?><fontconfig><dir>{HERE}</dir>'
                    f'<include ignore_missing="yes">/etc/fonts/fonts.conf</include><cachedir>{tmp}</cachedir></fontconfig>')
        os.environ['FONTCONFIG_FILE'] = conf
        masks = [(sym,) + render(px) for sym, px in SIZES]
    with open(out, 'w') as f:
        f.write('/* Generated by ui/assets/logo2a8.py from logo.svg (A8 alpha masks, cropped). Do not edit. */\n')
        f.write('#include "lvgl.h"\n')
        for sym, w, h, data in masks:
            f.write(f'\nstatic const uint8_t {sym}_map[] = {{\n')
            for i in range(0, len(data), 24):
                f.write('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',\n')
            f.write('};\n')
            f.write(f'const lv_image_dsc_t {sym} = {{\n'
                    f'    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w}}},\n'
                    f'    .data_size = sizeof({sym}_map),\n    .data = {sym}_map,\n}};\n')
            print(f'{out}: {sym} {w}x{h}, {len(data)} bytes')


main()
