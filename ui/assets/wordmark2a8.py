"""Rasterise the product name, set in a display font, into LVGL A8 masks (ui/wordmark_a8.c), tinted by the UI.

Usage: python3 wordmark2a8.py "Dice Spark" "licensed/Original Motion.ttf" ../wordmark_a8.c
The font itself is not embedded in the firmware and not committed (personal-use licence, see README.md): only the
rendered name is. Same renderer as logo2a8.py (PyGObject, GdkPixbuf, librsvg); the font is made visible through a
temporary fontconfig file.
"""
import os
import subprocess
import sys
import tempfile

SIZES = (("ui_wordmark_a8", 220), ("ui_wordmark_small_a8", 170))  # target width in px


def render(svg_path, text, family, px):
    import gi
    gi.require_version('GdkPixbuf', '2.0')
    from gi.repository import GdkPixbuf
    w, h = px * len(text), px * 3
    with open(svg_path, 'w') as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}"><text x="{px}" y="{px * 2}" '
                f'font-family="{family}" font-size="{px}" fill="#fff">{text}</text></svg>')
    p = GdkPixbuf.Pixbuf.new_from_file(svg_path)
    stride, raw = p.get_rowstride(), p.get_pixels()
    rows = [bytes(raw[y * stride + 4 * x + 3] for x in range(w)) for y in range(h)]
    ys = [y for y, r in enumerate(rows) if any(r)]
    xs = [x for x in range(w) if any(r[x] for r in rows)]
    x0, x1, y0, y1 = xs[0], xs[-1] + 1, ys[0], ys[-1] + 1
    return x1 - x0, y1 - y0, b''.join(r[x0:x1] for r in rows[y0:y1])


def main():
    text, font, out = sys.argv[1], os.path.abspath(sys.argv[2]), sys.argv[3]
    family = subprocess.run(['fc-scan', '-f', '%{family}', font], capture_output=True, text=True, check=True).stdout
    with tempfile.TemporaryDirectory() as tmp:
        conf = os.path.join(tmp, 'fonts.conf')
        with open(conf, 'w') as f:
            f.write(f'<?xml version="1.0"?><fontconfig><dir>{os.path.dirname(font)}</dir><cachedir>{tmp}</cachedir>'
                    f'</fontconfig>')
        os.environ['FONTCONFIG_FILE'] = conf
        svg = os.path.join(tmp, 't.svg')
        probe = render(svg, text, family, 100)[0]  # width at 100 px gives the size for each target width
        masks = [(sym,) + render(svg, text, family, round(100 * width / probe)) for sym, width in SIZES]
    with open(out, 'w') as f:
        f.write(f'/* Generated by ui/assets/wordmark2a8.py: "{text}" set in {family} (A8 alpha masks). Do not edit. */\n')
        f.write('#include "lvgl.h"\n')
        for sym, w, h, data in masks:
            f.write(f'\nstatic const uint8_t {sym}_map[] = {{\n')
            for i in range(0, len(data), 24):
                f.write('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',\n')
            f.write('};\n')
            f.write(f'const lv_image_dsc_t {sym} = {{\n'
                    f'    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w}}},\n'
                    f'    .data_size = sizeof({sym}_map),\n    .data = {sym}_map,\n}};\n')
            print(f'{out}: {sym} {w}x{h}, {len(data)} bytes')


main()
