"""Rasterise a one-colour SVG (absolute M/C/L/Z paths, evenodd) into an LVGL A8 image C file.

The A8 image is an alpha mask: the UI tints it with the seat hue at draw time, so the SVG colour is irrelevant.
Usage: python3 svg2a8.py <in.svg> <out.c> <symbol> <size_px> [margin_px]
Stdlib only; 4x4 supersampling for antialiasing.
"""
import re
import sys


def parse_paths(svg):
    edges = []
    for d in re.findall(r'<path[^>]*\sd="([^"]+)"', svg):
        toks = re.findall(r'[MCLZmclz]|-?\d*\.?\d+(?:e-?\d+)?', d)
        i, cur, start, poly = 0, None, None, []
        def num():
            nonlocal i
            v = float(toks[i]); i += 1; return v
        cmd = None
        while i < len(toks):
            if toks[i] in 'MCLZ':
                cmd = toks[i]; i += 1
            elif toks[i] in 'mclz':
                raise SystemExit('relative path commands not supported')
            if cmd == 'M':
                cur = start = (num(), num()); poly.append(cur); cmd = 'L'
            elif cmd == 'L':
                p = (num(), num()); poly.append(p); cur = p
            elif cmd == 'C':
                c1, c2, p = (num(), num()), (num(), num()), (num(), num())
                for k in range(1, 17):
                    t = k / 16; u = 1 - t
                    poly.append((u**3*cur[0] + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p[0],
                                 u**3*cur[1] + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p[1]))
                cur = p
            elif cmd == 'Z':
                poly.append(start)
                edges += list(zip(poly, poly[1:]))
                poly, cmd = [], None
        if poly:
            edges += list(zip(poly, poly[1:] + poly[:1]))
    return edges


def main():
    src, out, sym, size = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
    margin = int(sys.argv[5]) if len(sys.argv) > 5 else 2
    edges = parse_paths(open(src).read())
    xs = [p[0] for e in edges for p in e]; ys = [p[1] for e in edges for p in e]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    span = max(x1 - x0, y1 - y0)
    scale = (size - 2 * margin) / span
    ox = margin + ((size - 2 * margin) - (x1 - x0) * scale) / 2 - x0 * scale
    oy = margin + ((size - 2 * margin) - (y1 - y0) * scale) / 2 - y0 * scale
    E = [((a[0]*scale+ox, a[1]*scale+oy), (b[0]*scale+ox, b[1]*scale+oy)) for a, b in edges]
    SS = 4
    img = [[0] * size for _ in range(size)]
    for py in range(size * SS):
        y = (py + 0.5) / SS
        xs_ = sorted(a[0] + (y - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
                     for a, b in E if (a[1] <= y < b[1]) or (b[1] <= y < a[1]))
        for k in range(0, len(xs_) - 1, 2):  # evenodd spans
            for sx in range(max(0, int(xs_[k] * SS + 0.5)), min(size * SS, int(xs_[k + 1] * SS + 0.5))):
                img[py // SS][sx // SS] += 1
    data = bytes(min(255, v * 255 // (SS * SS)) for row in img for v in row)
    with open(out, 'w') as f:
        f.write(f'/* Generated by ui/assets/svg2a8.py from {src.split("/")[-1]} ({size}x{size} A8 alpha mask). Do not edit. */\n')
        f.write('#include "lvgl.h"\n\n')
        f.write(f'static const uint8_t {sym}_map[] = {{\n')
        for i in range(0, len(data), 24):
            f.write('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i+24]) + ',\n')
        f.write('};\n\n')
        f.write(f'const lv_image_dsc_t {sym} = {{\n'
                f'    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {size}, .h = {size}, .stride = {size}}},\n'
                f'    .data_size = sizeof({sym}_map),\n    .data = {sym}_map,\n}};\n')
    cov = sum(1 for b in data if b > 127) / len(data)
    print(f'{out}: {size}x{size}, {len(data)} bytes, coverage {cov:.0%}')


main()
