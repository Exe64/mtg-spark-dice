"""Generate the luminous theme's glowing ring, ray and line icons as LVGL A8 alpha masks (ui/fx_a8.c).

The UI tints the masks at draw time (ui/fx.c). Halos are not here: ui/fx.c computes one mask per radius and caches it.
Usage: python3 glow_gen.py ../fx_a8.c
Stdlib only. Provenance: every mask is computed by this script, no external source.
"""
import math
import sys

RING = 128           # glowing ring; RING_R is its radius at native size
RING_R = 48
RAY_W, RAY_H = 32, 128  # beam leaving the top-centre pixel, pointing down
ICON = 40            # line icons, 2.5 px round-capped stroke
STROKE = 2.5


def clamp8(v):
    return max(0, min(255, int(v * 255 + 0.5)))


def ring():
    c, sigma = (RING - 1) / 2, 5.5
    out = []
    for y in range(RING):
        for x in range(RING):
            d = math.hypot(x - c, y - c)
            a = math.exp(-0.5 * ((d - RING_R) / sigma) ** 2)
            out.append(clamp8(a - 0.02) if d < RING / 2 else 0)
    return out


def ray():
    c = (RAY_W - 1) / 2
    out = []
    for y in range(RAY_H):
        t = y / (RAY_H - 1)
        width = 2.5 + 4.5 * t                 # the beam widens as it travels
        fade = (1 - t) ** 0.55 * min(1, y / 6)  # and fades late: it must still read near the rim
        for x in range(RAY_W):
            out.append(clamp8(math.exp(-0.5 * ((x - c) / width) ** 2) * fade))
    return out


# ---- icons: polylines in a 40x40 box --------------------------------------------------------------------------------

def arc(cx, cy, r, a0, a1, n=24):
    """Polyline along a circle, angles in degrees (0 = right, 90 = down)."""
    return [(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def circle(cx, cy, r):
    return arc(cx, cy, r, 0, 360, 32)


def gear():
    teeth = []
    for i in range(8):
        a = math.radians(i * 45)
        teeth.append([(20 + 10.5 * math.cos(a), 20 + 10.5 * math.sin(a)), (20 + 15 * math.cos(a), 20 + 15 * math.sin(a))])
    return [circle(20, 20, 9.5), circle(20, 20, 3.5)] + teeth


ICONS = [
    ("settings", gear()),
    ("players", [circle(20, 13, 5.5), arc(20, 35, 12.5, 200, 340)]),
    ("resume", [[(14, 9), (31, 20), (14, 31), (14, 9)]]),
    ("game", [[(9, 13), (23, 13), (23, 34), (9, 34), (9, 13)], [(15, 9), (15, 6), (31, 6), (31, 28), (27, 28)]]),
    ("undo", [arc(21, 22, 10.5, 200, 480), [(5, 12), (11.1, 18.4), (17.5, 13)]]),
    ("turn", [[(6, 20), (27, 20)], [(19, 11), (28, 20), (19, 29)], [(34, 9), (34, 31)]]),
    ("wifi", [arc(20, 31, 6, 225, 315), arc(20, 31, 13, 225, 315), arc(20, 31, 20, 225, 315), circle(20, 31, 1)]),
    ("room", [circle(20, 9, 4.5), circle(8, 30, 4.5), circle(32, 30, 4.5),
              [(17.6, 12.9), (10.4, 26.1)], [(22.4, 12.9), (29.6, 26.1)], [(12.5, 30), (27.5, 30)]]),
]


def seg_dist(px, py, a, b):
    ax, ay, bx, by = a[0], a[1], b[0], b[1]
    dx, dy = bx - ax, by - ay
    L = dx * dx + dy * dy
    t = 0 if L == 0 else max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / L))
    return math.hypot(px - ax - t * dx, py - ay - t * dy)


def icon(polys):
    segs = [(p[i], p[i + 1]) for p in polys for i in range(len(p) - 1)]
    out = []
    for y in range(ICON):
        for x in range(ICON):
            d = min(seg_dist(x + 0.5, y + 0.5, a, b) for a, b in segs)
            out.append(clamp8(STROKE / 2 - d + 0.5))  # distance-field antialiasing
    return out


def emit(f, sym, w, h, data):
    f.write(f'static const uint8_t {sym}_map[] = {{\n')
    for i in range(0, len(data), 24):
        f.write('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',\n')
    f.write('};\n')
    return (f'{{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {w}, .h = {h}, .stride = {w}}},'
            f' .data_size = sizeof({sym}_map), .data = {sym}_map}}')


def main():
    out = sys.argv[1]
    with open(out, 'w') as f:
        f.write('/* Generated by ui/assets/glow_gen.py (A8 alpha masks: ring, ray, line icons). Do not edit. */\n')
        f.write('#include "lvgl.h"\n\n')
        for sym, w, h, data in (("fx_ring_a8", RING, RING, ring()), ("fx_ray_a8", RAY_W, RAY_H, ray())):
            dsc = emit(f, sym, w, h, data)
            f.write(f'const lv_image_dsc_t {sym} = {dsc};\n\n')
        dscs = [emit(f, f'fx_icon_{name}', ICON, ICON, icon(polys)) for name, polys in ICONS]
        f.write(f'\n/* order = fx_icon_t (ui/fx.h): {", ".join(n for n, _ in ICONS)} */\n')
        f.write(f'const lv_image_dsc_t fx_icons_a8[{len(ICONS)}] = {{\n')
        for d in dscs:
            f.write(f'    {d},\n')
        f.write('};\n')
    print(f'{out}: ring {RING}x{RING} (r={RING_R}), ray {RAY_W}x{RAY_H}, {len(ICONS)} icons {ICON}x{ICON}')


main()
