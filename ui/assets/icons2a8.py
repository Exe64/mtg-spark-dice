"""Rasterise the icons supplied by the owner (icons/) into LVGL A8 masks: the home screen's, and the markers'.

Usage: python3 icons2a8.py ../home_icons_a8.c
Only the alpha channel is kept: the UI tints the masks. Renderer: PyGObject with GdkPixbuf and librsvg, as logo2a8.py.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HOME = (("settings", "settings.svg", 34), ("update", "update.png", 34), ("host", "host.png", 44), ("join", "join.png", 44))
# markers panel: order = MARKER_ICON in ui/ui.c; the others keep their 3-letter label until their icon arrives
MARKERS = (("energy", "energy.png", 46), ("rad", "rad.png", 46), ("day", "day.png", 46), ("night", "night.png", 46))  # = a chip
GROUPS = (("ui_home_icons_a8", "home", HOME), ("ui_marker_icons_a8", "marker", MARKERS))


def alpha(path, px):
    import gi
    gi.require_version('GdkPixbuf', '2.0')
    from gi.repository import GdkPixbuf
    p = GdkPixbuf.Pixbuf.new_from_file_at_size(path, px, px)
    assert p.get_has_alpha() and p.get_width() == px and p.get_height() == px
    stride, raw = p.get_rowstride(), p.get_pixels()
    return bytes(raw[y * stride + 4 * x + 3] for y in range(px) for x in range(px))


def main():
    with open(sys.argv[1], 'w') as f:
        f.write('/* Generated by ui/assets/icons2a8.py from ui/assets/icons/ (A8 alpha masks). Do not edit. */\n')
        f.write('#include "lvgl.h"\n')
        for array, prefix, icons in GROUPS:
            f.write('\n')
            for name, src, px in icons:
                data = alpha(os.path.join(HERE, 'icons', src), px)
                f.write(f'static const uint8_t {prefix}_{name}_map[] = {{\n')
                for i in range(0, len(data), 24):
                    f.write('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 24]) + ',\n')
                f.write('};\n')
            f.write(f'\n/* order: {", ".join(n for n, _, _ in icons)} */\nconst lv_image_dsc_t {array}[{len(icons)}] = {{\n')
            for name, _, px in icons:
                f.write(f'    {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {px}, .h = {px}, .stride = {px}}},'
                        f' .data_size = sizeof({prefix}_{name}_map), .data = {prefix}_{name}_map}},\n')
            f.write('};\n')
            print(f'{sys.argv[1]}: {array}: {", ".join(f"{n} {px}x{px}" for n, _, px in icons)}')


main()
